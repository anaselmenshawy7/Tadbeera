/**
 * Tier 3 Fallback: Guaranteed Dynamic Arabic Home Recipe Synthesizer.
 * Builds a complete, familySize-scalable, voice-ready Egyptian/Arabic home recipe
 * tailored to the user's exact query so no recipe search can ever hit a dead end.
 */
export function synthesizeDynamicArabicRecipe(rawQuery: string, _familySize = 4): OnlineRecipe {
  const dishName = cleanUserDishName(rawQuery);
  const normQuery = normalizeArabicSearchTerm(dishName);
  const template = selectCulinaryTemplate(normQuery);
  const baseServings = 4;

  const ingredientsList = template.ingredients(dishName);
  const stepsList = template.steps(dishName);
  const title = `طريقة عمل ${dishName} في البيت`;

  const extract =
    `المكونات (${baseServings} أفراد):\n` +
    `${ingredientsList.map(item => `• ${item}`).join('\n')}\n\n` +
    `طريقة التحضير:\n` +
    `${stepsList.map((step, index) => `${index + 1}. ${step}`).join('\n')}`;

  return {
    title,
    servings: baseServings,
    pageId: createStablePageId(normQuery || rawQuery),
    cuisine: template.cuisine,
    url: 'https://www.themealdb.com/',
    prepTime: template.prepTime,
    isSynthesized: true,
    extract,
  };
}
