function cleanUserDishName(rawQuery: string): string {
  const stripped = rawQuery
    .trim()
    .replace(/^(?:عايز|عاوزه|عاوز|عايزه|ابحث عن|دور على|ابغى|اريد)\s+/u, '')
    .replace(/^(?:طريقة عمل|طريقة تحضير|كيفية عمل|ازاي اعمل)\s+/u, '')
    .replace(/\s+(?:في البيت|بالبيت|على اصوله|على أصوله|بسهولة)\s*$/u, '')
    .replace(/\s+/g, ' ')
    .trim();
  return stripped || rawQuery.trim() || 'الأكلة المطلوبة';
}

function createStablePageId(seed: string): number {
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) {
    hash = (hash * 31 + seed.charCodeAt(i)) % 800000;
  }
  return 9900000 + Math.abs(hash);
}

