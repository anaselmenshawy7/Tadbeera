/**
 * Searches the built-in 160 Egyptian & Arabic recipe catalog across title, aliases,
 * category tags, and whole-word ingredients. Never returns unrelated dishes.
 */
export function searchEgyptianArabicCatalog(
  query: string,
  _familySize = 4
): Array<CatalogRecipeItem['recipe'] & { _relevanceScore: number }> {
  const matches: Array<CatalogRecipeItem['recipe'] & { _relevanceScore: number }> = [];
  for (const item of EGYPTIAN_ARABIC_CATALOG) {
    const score = scoreRecipeDishRelevance(
      query,
      item.recipe.title,
      item.terms,
      item.categories,
      item.ingredientsText
    );
    if (score > 0) {
      matches.push({
        ...item.recipe,
        _relevanceScore: score,
      });
    }
  }
  return matches.sort((a, b) => b._relevanceScore - a._relevanceScore);
}

