function deriveCatalogCategories(
  title: string,
  terms: string[],
  explicit?: RecipeCategoryTag[]
): RecipeCategoryTag[] {
  if (explicit && explicit.length > 0) return explicit;
  const text = `${title} ${terms.join(' ')}`;
  const cats = new Set<RecipeCategoryTag>();

  if (/محشي|ورق عنب|كرنب|ممبار/.test(text)) cats.add('محاشي');
  if (/مكرونة|نجرسكو|لازانيا/.test(text)) cats.add('مكرونات');
  if (/طاجن|صينية|عكاوي|تورلي|معمر/.test(text)) cats.add('طواجن');
  if (/مشوي|مشوية|حاتي|شيش|فحم|جريل|كباب/.test(text)) cats.add('مشويات');
  if (/فراخ|دجاج|ديك رومي|بط|حمام|أرانب|شيش طاووق|نجرسكو|شاورما فراخ|مسخن|كبسة دجاج|مندي دجاج|برياني دجاج|مقلوبة باذنجان وفراخ/.test(text)) {
    cats.add('دواجن');
  }
  if (/لحم|لحمة|كفتة|كبيبة|سجق|كبدة|عكاوي|ممبار|داوود|حواوشي|شاورما لحمة|منسف|برجر|لازانيا|جلاش باللحمة|رقاق/.test(text)) {
    cats.add('لحوم');
  }
  if (/فطير|قرص|سمبوسك|جلاش بالجبنة|جلاش باللحمة|رقاق|بيتزا|باتيه|مناقيش|خلية نحل|كرواسون/.test(text)) {
    cats.add('معجنات');
  }
  if (/فطير|قرص|فايش|شابورة|كحك|غريبة|بيتي فور|عيش|باتيه|مناقيش|خلية نحل|كرواسون/.test(text)) {
    cats.add('مخبوزات');
  }
  if (/بسبوسة|كنافة|أم علي|قطايف|زلابية|بلح الشام|جلاش حلو|أرز بلبن|مهلبية|كحك|غريبة|بيتي فور|حلويات|كيكة|دوناتس|سينابون|بقلاوة|صوابع زينب|رموش الست/.test(text)) {
    cats.add('حلويات');
  }
  if (/فول|طعمية|شكشوكة|عجة|بطاطس مهروسة|فطير|قرص|فايش|شابورة|سمبوسك|باتيه|مناقيش/.test(text)) {
    cats.add('فطار');
  }
  if (/شاورما|حواوشي|برجر|سجق|كبدة|ساندوتش|كريب|زنجر|مسحب/.test(text)) {
    cats.add('سندوتشات');
  }
  if (/سمك|جمبري|سبيط|سي فود/.test(text)) {
    cats.add('مأكولات بحرية');
  }
  if (/شوربة|تبولة|فتوش|حمص|بابا غنوج/.test(text)) {
    cats.add('شوربة وسلطات');
  }
  if (cats.size === 0) {
    cats.add('أطباق رئيسية');
  }

  return Array.from(cats);
}

