/**
 * Backup culinary English-to-Arabic dictionary translator used when remote
 * machine translation leaves residual Latin terms or is temporarily throttled.
 */
export function applyCulinaryDictionaryToArabic(text: string): string {
  let result = text;
  for (const [pattern, arabic] of ENGLISH_TO_ARABIC_CULINARY_TERMS) {
    result = result.replace(pattern, arabic);
  }
  return result.replace(/\s+/g, ' ').trim();
}
