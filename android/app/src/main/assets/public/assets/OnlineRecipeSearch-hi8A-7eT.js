async function translateText(value, source, target) {
	const text = value.trim();
	if (!text || source === target) return text;
	const sentences = text.match(/[^.!?。！？\n]+[.!?。！？\n]*/g) || [text];
	const chunks = [];
	let current = "";
	for (const sentence of sentences) if (current.length + sentence.length > 1200 && current) {
		chunks.push(current);
		current = sentence;
	} else current += sentence;
	if (current) chunks.push(current);
	const translated = [];
	for (const chunk of chunks) try {
		const url = new URL("https://translate.googleapis.com/translate_a/single");
		url.search = new URLSearchParams({
			client: "gtx",
			sl: source,
			tl: target,
			dt: "t",
			q: chunk
		}).toString();
		const response = await fetch(url.toString());
		if (!response.ok) throw new Error("translation-failed");
		const data = await response.json();
		const output = Array.isArray(data?.[0]) ? data[0].map((part) => typeof part?.[0] === "string" ? part[0] : "").join("") : "";
		if (!output.trim()) throw new Error("empty-translation");
		if (target === "ar" && !hasArabic(output)) throw new Error("arabic-translation-unavailable");
		translated.push(output);
	} catch (error) {
		if (target === "ar") throw error;
		translated.push(chunk);
	}
	return translated.join("");
}
