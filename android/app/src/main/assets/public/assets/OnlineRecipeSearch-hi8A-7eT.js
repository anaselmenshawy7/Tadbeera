/**
* Searches the built-in 105+ Egyptian & Arabic recipe catalog strictly by dish title/aliases.
* Never returns unrelated dishes (e.g., searching "ديك رومي" will never match "فلفل رومي").
*/
function searchEgyptianArabicCatalog(query, _familySize = 4) {
	const matches = [];
	for (const item of EGYPTIAN_ARABIC_CATALOG) {
		const score = scoreRecipeDishRelevance(query, item.recipe.title, item.terms);
		if (score > 0) matches.push({
			...item.recipe,
			_relevanceScore: score
		});
	}
	return matches.sort((a, b) => b._relevanceScore - a._relevanceScore);
}
