function normalizeArabicSearchTerm(value) {
	return value.toLocaleLowerCase("ar").normalize("NFKC").replace(/[\u064B-\u065F\u0670\u0640]/g, "").replace(/[أإآٱ]/g, "ا").replace(/ى/g, "ي").replace(/[ؤئ]/g, "ء").replace(/ة/g, "ه").replace(/[ًٌٍَُِّْـ]/g, "").replace(/[^\p{L}\p{N}\s]/gu, " ").replace(/\s+/g, " ").trim();
}
function matchesArabicSearchAlias(query, alias) {
	const normalizedQuery = normalizeArabicSearchTerm(query);
	const normalizedAlias = normalizeArabicSearchTerm(alias);
	if (!normalizedQuery || !normalizedAlias) return false;
	if (normalizedQuery === normalizedAlias) return true;
	return ` ${normalizedQuery} `.includes(` ${normalizedAlias} `);
}
